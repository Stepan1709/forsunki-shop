"""Классы ошибок обработки сообщений.

От класса ошибки зависит судьба сообщения:
  TemporaryError  сбой, который может пройти сам (БД недоступна, сервис вернул 503): повторить позже.
  PermanentError  повтор не поможет (битый JSON, неизвестная версия схемы, нарушение бизнес-правила):
                  сразу в DLQ на разбор человеком.
  Любое другое исключение считаем постоянным: неизвестная ошибка чаще всего баг в коде, и бесконечные
  повторы только засорили бы очереди и скрыли проблему.
"""


class TemporaryError(Exception):
    """Временная ошибка: сообщение будет повторено с задержкой."""


class PermanentError(Exception):
    """Постоянная ошибка: сообщение сразу уходит в DLQ."""


class PublishFailed(Exception):
    """Брокер не подтвердил публикацию или вернул сообщение (некуда доставить)."""


class Unroutable(PublishFailed):
    """Брокер вернул сообщение: нет очереди, которой оно адресовано (например, подписчик ещё не развёрнут).

    Отличается от общего PublishFailed: проблема в конкретном сообщении, а не в брокере, поэтому остальные
    сообщения публиковать можно, а это нужно отложить и повторить позже.
    """
